/**
 * 적응형 전투 난이도 단계.
 *
 * 🔴 **왜 단계가 필요한가 — 숫자 하나로는 두 아이를 못 맞춘다(실측).**
 *    2026-08-01 긴장도 실측(21시드 × 9판 × 정답률 4구간):
 *      · 지금 밸런스에서 정답 80%·95% 아이는 **378판 중 진 판 0, 우리 성이 맞은 판 0.**
 *        이길지 질지가 아니라 구경만 하는 상태다. 사용자 보고 "너무 쉬워서 노잼".
 *      · 손잡이를 다 돌려 봤다. **적 체력 ×4 → 아무 변화 없음**(적이 성문에서 한 마리씩
 *        16대1로 죽을 뿐), **스폰간격 ×0.1(몰려오게) → 거의 변화 없음.**
 *      · 유일하게 듣는 건 적 공격력인데, ×3이면 정답 40% 아이가 89% 지고,
 *        ×7이어도 정답 95% 아이는 **0% 진다.** 한 값으로 둘을 동시에 못 맞춘다.
 *    원인은 되먹임에 반대 힘이 없다는 것이다 — 잘 맞힐수록 셈력↑ → 유닛↑ → 신바람↑ →
 *    더 빨리 죽임 → 더 여유. 그래서 난이도를 **아이별로** 움직인다.
 *
 * 🔴 **0단계는 오늘의 밸런스와 정확히 같아야 한다.** 그래야 "정답 60% 아이가 소환 없이
 *    캠페인을 통과한다"(G2)가 *설계상* 보장된다 — 못하는 아이는 0단계를 벗어나지 않으므로
 *    게이트가 검사하는 그 밸런스를 그대로 만난다. `tests/tier.spec.ts` 가 이걸 감시한다.
 */

/** 0 = 안전망 기준선(오늘 밸런스), 위로 갈수록 도전적 */
export const MAX_TIER = 8;

/** 적 공격력 배율. 실측 기준점: ×3 에서 정답80% 아이가 6% 패배, ×5 에서 17%, ×7 에서 40% */
// 🔴 위로 갈수록 **비율**이 완만해지면(1.70→1.21) 상위 단계에서 한 칸 올라가도
//    별로 안 아프고, 적응 루프의 균형점에서 거의 지지 않는다(실측: 정답 95% 아이
//    패배율 2.86% — G8-b 하한 3% 미달). 4단계부터 배율을 ×1.35 로 고정한다.
//    0단계는 손대지 않는다 — G2 안전망의 근거다.
const ATK: readonly number[] = [1.0, 1.7, 2.6, 3.6, 4.9, 6.6, 8.9, 12.0, 16.2];

/**
 * 돌파형 비율 — 이 비율만큼의 적이 **전선을 무시하고 우리 성으로 직행**한다.
 * 🔴 물량·체력이 안 듣는 이유가 "우리 상비군 16기가 길목을 완전히 막는다"였다.
 *    돌파형은 그 길목 자체를 우회하므로, 아무리 쌓아도 새는 놈이 생긴다 —
 *    원거리·빠른 셈지기를 뽑을 이유(=덱 구성의 의미)가 여기서 처음 생긴다.
 */
const BREAK: readonly number[] = [0, 0.15, 0.25, 0.34, 0.42, 0.50, 0.58, 0.64, 0.70];

/**
 * 광역 공격 반경(월드 단위). 0 이면 광역 없음.
 * 🔴 "16기 쌓고 방치"를 정면으로 무력화한다. 뭉쳐 있을수록 손해가 되어야
 *    전선이 무너졌다 다시 서는 순간이 생긴다.
 */
const AOE: readonly number[] = [0, 0, 70, 85, 100, 115, 130, 145, 160];

/**
 * 전투 중 문항 목표 정답률.
 * 🔴 0.85 로 고정돼 있어서 문항 레벨 3~5 가 30판 내내 **한 번도** 안 나왔다
 *    (실측: Lv1 589 / Lv2 71 / Lv3~5 0). 목표 정답률을 0.85 로 두면 문항은 아이보다
 *    302 Elo 아래로만 골라지기 때문이다. 단계와 함께 낮춘다.
 * 🔴 전투와 묶여 있다는 걸 잊지 말 것 — 정답률이 떨어지면 셈력도 줄어 전투가 같이
 *    어려워진다. 그래서 문항 목표를 **따로** 놀리지 않고 이 단계 하나에 묶는다.
 * 🔴 바닥을 0.72 로 두었다가 되돌렸다. 30판 실측에서 **체감 정답률이 62%** 로 떨어졌는데,
 *    열 문제 중 넷을 틀리는 건 저학년에게 도전이 아니라 벌이다. 목표 0.77 이면 체감 ~73%,
 *    평균 레벨 1.15 → 1.9 로 사다리는 열리면서 좌절선은 넘지 않는다(실측 대응표):
 *      목표 0.85→체감 84%(Lv1.15) · 0.80→77%(1.58) · 0.77→~73%(1.9) · 0.72→62%(2.42)
 */
// 🔴 문항 목표는 0.77(체감 ~73%)에서 **멈춘다.** 전투는 계속 어려워져도 되지만,
//    문제를 계속 어렵게 하는 건 다른 문제다 — 저학년에게 좌절선을 넘기지 않는다.
//    아주 잘하는 아이에게는 전투 쪽(공격력·돌파·광역)만 더 올린다.
const TARGET_P: readonly number[] = [0.85, 0.84, 0.82, 0.81, 0.79, 0.78, 0.77, 0.77, 0.77];

/**
 * 단계 값을 안전한 정수 범위로 자른다.
 * 🔴 `Number.isFinite` 검사를 빼면 NaN 이 그대로 통과한다 —
 *    `Math.max(0, Math.min(N, Math.floor(NaN)))` 는 0 이 아니라 **NaN** 이다.
 *    (실측: Battle 생성자가 자체 클램프를 쓰다 tier=NaN 을 그대로 들고 있었다.
 *     그 값이 결과 화면의 `nextTier !== tier` 비교에 들어가면 항상 참이 되어
 *     난이도가 안 바뀐 판에도 "더 세졌어요" 안내가 뜬다.)
 *    클램프는 **이 함수 하나만** 쓴다.
 */
export const clampTier = (t: number): number =>
  Math.max(0, Math.min(MAX_TIER, Math.floor(Number.isFinite(t) ? t : 0)));

export const tierAtk = (t: number): number => ATK[clampTier(t)]!;
export const tierBreakShare = (t: number): number => BREAK[clampTier(t)]!;
export const tierAoe = (t: number): number => AOE[clampTier(t)]!;
export const tierTargetP = (t: number): number => TARGET_P[clampTier(t)]!;

/** 판이 끝난 뒤 다음 판의 난이도를 정한다. */
export interface MatchOutcome {
  win: boolean;
  /** 우리 성 남은 비율 0~1 */
  castleLeft: number;
  /** 이 판의 정답률 0~1 */
  accuracy: number;
}

/**
 * 🔴 **올릴 땐 천천히, 내릴 땐 즉시.** 한 판 잘 풀렸다고 바로 올리면 운 좋은 판 하나로
 *    아이가 벽을 만난다. 반대로 졌을 때는 다음 판에서 바로 물러나야 "막혔다"가 안 된다.
 *    비대칭이 의도다.
 */
export const EASY_STREAK_TO_RAISE = 2;

export function nextTier(tier: number, streak: number, m: MatchOutcome):
  { tier: number; streak: number } {
  const t = clampTier(tier);
  if (!m.win) return { tier: clampTier(t - 1), streak: 0 };
  // 여유롭게 이겼다 = 성이 거의 안 깎였고 문제도 잘 맞혔다
  const comfortable = m.castleLeft >= 0.85 && m.accuracy >= 0.7;
  if (!comfortable) return { tier: t, streak: 0 };   // 딱 맞는 난이도 — 유지
  const s = streak + 1;
  return s >= EASY_STREAK_TO_RAISE ? { tier: clampTier(t + 1), streak: 0 } : { tier: t, streak: s };
}
