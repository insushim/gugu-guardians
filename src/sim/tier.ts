/**
 * 적응형 전투 난이도 단계.
 *
 * 🔴 **왜 단계가 필요한가 — 숫자 하나로는 두 아이를 못 맞춘다(실측).**
 *    2026-08-01 긴장도 실측(21시드 × 9판 × 정답률 4구간):
 *      · 지금 밸런스에서 정답 80%·95% 아이는 **378판 중 진 판 0, 우리 성이 맞은 판 0.**
 *        이길지 질지가 아니라 구경만 하는 상태다. 사용자 보고 "너무 쉬워서 노잼".
 *      · 손잡이를 다 돌려 봤다. **적 체력 ×4 → 아무 변화 없음**(적이 성문에서 한 마리씩
 *        16대1로 죽을 뿐), **스폰간격 ×0.1(몰려오게) → 거의 변화 없음.**
 *      · 유일하게 듣는 건 적 공격력인데, ×3이면 정답 40% 아이가 89% 지고,
 *        ×7이어도 정답 95% 아이는 **0% 진다.** 한 값으로 둘을 동시에 못 맞춘다.
 *    원인은 되먹임에 반대 힘이 없다는 것이다 — 잘 맞힐수록 셈력↑ → 유닛↑ → 신바람↑ →
 *    더 빨리 죽임 → 더 여유. 그래서 난이도를 **아이별로** 움직인다.
 *
 * 🔴 **0단계는 오늘의 밸런스와 정확히 같아야 한다.** 그래야 "정답 60% 아이가 소환 없이
 *    캠페인을 통과한다"(G2)가 *설계상* 보장된다 — 못하는 아이는 0단계를 벗어나지 않으므로
 *    게이트가 검사하는 그 밸런스를 그대로 만난다. `tests/tier.spec.ts` 가 이걸 감시한다.
 */

/**
 * 0 = 안전망 기준선(오늘 밸런스), 위로 갈수록 도전적.
 *
 * 🔴 8 이었다. 그런데 정답 95% 아이가 평균 5.1단계에 앉아 **30판 중 진 판이 2판**이었다 —
 *    천장이 낮아 적응 루프가 그 아이를 위협할 자리까지 데려가지 못한 것이다.
 *    12로 늘리고(아래 표 연장) 오르는 속도도 함께 올렸다(nextTier 의 '압도' 규칙).
 *
 * 🔴 12 였다 → 20. **빠른 풀이자에게는 천장이 아예 없었다**(2026-08-20 실측).
 *    그때까지 밸런스 프로브는 실력을 *정답률 하나*로만 모델링했는데, 이 게임에서
 *    셈력(자원)은 정답에서 나오므로 실력은 두 축이다 — **얼마나 맞히나 · 얼마나 빨리 맞히나.**
 *    프로브의 응답 시간은 `tOk(acc)=2.3+(1-acc)*2.4` 라서 **가장 빠른 플레이어조차
 *    문항당 2.3초**였고, 구구단을 1초에 답하는 사람(어른·숙달 아동)은 게이트가
 *    한 번도 본 적이 없었다. 그래서 프로브는 "정답 95% 아이 패배율 40%"라고 초록불을 켰고,
 *    실사용자는 같은 빌드를 "너무 쉽다"고 네 번째로 보고했다.
 *    `tools/speed-probe.mjs` 로 속도 축을 넣고 재니 이렇게 나왔다(정답률 95% 고정):
 *      · 보통 아이(2.4s/문항) 패배율 40% · 성 피격률 50%   ← 게이트가 보던 것
 *      · 어른     (1.0s/문항) 패배율  3% · 성 피격률  6%   ← 실사용자
 *    그리고 **단계를 당시 최고(12)에 못 박아도 어른 승률 99%** 였다.
 *
 * 🔴 20 인 이유 — **공격력만으로는** 그 위가 안 듣는다. 당시 ×1.35 로 22까지 늘려 스윕한
 *    결과(단계 고정, 어른 정답95% 승률):
 *      12:99% · 13:88% · 15:67% · 17:52% · 19:49% · 20:45% · 21:50% · 22:55%
 *    21부터 **다시 올라간다.** 돌파 비율이 이미 0.95라 새는 적은 전부 새고, 공격력을
 *    더 줘도 이미 한 방에 죽는 것을 두 방에 죽일 뿐이라 아무것도 바뀌지 않는다.
 *    그래서 답은 "표를 더 늘린다"가 아니라 **새 축**이었다 — 아래 VOL(물량)이 그것이다.
 *    포화를 새 축으로 풀었으므로 천장은 20에서 멈춘다.
 */
